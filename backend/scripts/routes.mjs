// Prints every API URL, found by reading the source: `npm run routes` (or `npm run routes > API.md`).
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, resolve } from "node:path";

const SRC = resolve(import.meta.dirname, "../src");
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(SRC).filter((f) => f.endsWith(".ts"));

// 1. which prefix each router is mounted at (src/app.ts)
const app = readFileSync(join(SRC, "app.ts"), "utf8");
const mounts = {};
for (const m of app.matchAll(/app\.use\(\s*"([^"]+)"\s*,\s*(?:[\w.()", ]*?,\s*)?(\w+Router)\s*\)/g)) (mounts[m[2]] ??= []).push(m[1]);

// 2. routes of each router
const rows = [];
for (const f of files) {
  const src = readFileSync(f, "utf8");
  const roles = {};
  for (const m of src.matchAll(/(\w+Router)\.use\(\s*auth\(([^)]*)\)\s*\)/g)) roles[m[1]] = m[2].replace(/["\s]/g, "") || "any login";
  for (const m of src.matchAll(/(\w+Router)\.(get|post|put|patch|delete)\(\s*["'`]([^"'`]*)["'`]\s*,?([^\n]*)/g)) {
    const [, name, method, path, rest] = m;
    const inline = /auth\(([^)]*)\)/.exec(rest);
    const who = inline ? inline[1].replace(/["\s]/g, "") || "any login" : roles[name] ?? "public";
    for (const prefix of mounts[name] ?? []) rows.push({ url: (prefix + (path === "/" ? "" : path)).replace(/\/$/, "") || "/", method: method.toUpperCase(), who, file: f.slice(SRC.length + 1) });
  }
}
rows.sort((a, b) => a.url.localeCompare(b.url) || a.method.localeCompare(b.method));
console.log("# ScootMeal API\n\nGenerated by `npm run routes`. JSON in and out; errors look like `{ \"error\": \"message\" }`; send `Authorization: Bearer <token>` for anything not public.\n");
console.log("| Method | URL | Who | Code |\n|---|---|---|---|");
for (const r of rows) console.log(`| ${r.method} | \`${r.url}\` | ${r.who} | ${r.file} |`);
console.log(`\n${rows.length} routes.`);
